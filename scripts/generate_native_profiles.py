"""Validate local R1 MEM targets and emit elaboration constants/identity.

Does not checkout CModel, select a different reference, or change profile0.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sha(p):
    return hashlib.sha256(p.read_bytes()).hexdigest()


def generate():
    index_path = ROOT / 'config/native_profiles.json'
    index = json.loads(index_path.read_text(encoding='utf-8'))
    cm = (ROOT / index['cmodel_working_reference']).resolve()
    rows = []
    for profile, tiles, depth in [(16, 2, 1024), (32, 4, 2048), (64, 8, 2048)]:
        path = cm / index['profiles'][str(profile)]
        data = json.loads(path.read_text(encoding='utf-8'))
        geom = (data['topology']['hemispheres'], data['topology']['tiles_per_slice'],
                data['topology']['lanes_per_tile'], data['mem']['slices_per_hemisphere'],
                data['mem']['banks_per_slice'], data['mem']['rows_per_bank'],
                data['stream_topology']['bindings']['mem']['slices_per_group'],
                data['sr']['registers_per_lane'])
        if geom != (2, tiles, 8, 52, 2, depth, 4, 64):
            raise ValueError(f'profile {profile}: inconsistent MEM geometry {geom}')
        columns = data['stream_topology']['fabric_template']['columns']
        boundaries = data['stream_topology']['bindings']['mem']['boundary_columns']
        if len(columns) != 16 or boundaries != columns[:14]:
            raise ValueError(f'profile {profile}: incompatible horizontal topology')
        rows.append(dict(profile=profile, tiles=tiles, physical_rows=depth, active_rows=depth,
                         hemispheres=2, slices_per_hemisphere=52, banks_per_slice=2,
                         slices_per_group=4, lanes_per_tile=8, streams_per_direction=32,
                         columns=16, mem_boundaries=14, leaf_count=208*tiles,
                         capacity_bytes=208*tiles*depth*8,
                         cmodel_target=index['profiles'][str(profile)], target_sha256=sha(path)))
    lines = ['// Generated by scripts/generate_native_profiles.py; do not hand edit.',
             'package lpu_native_config_pkg;',
             '  function automatic integer profile_valid(input integer profile);',
             '    profile_valid = (profile == 0 || profile == 16 || profile == 32 || profile == 64);',
             '  endfunction']
    for function, field in [('tile_rows', 'tiles'), ('mem_depth_rows', 'physical_rows')]:
        lines += [f'  function automatic integer {function}(input integer profile);', '    case (profile)']
        lines += [f'      {r["profile"]}: {function} = {r[field]};' for r in rows]
        # Profile0 must be handled by the caller's existing legacy parameters.
        lines += [f'      default: {function} = 0;', '    endcase', '  endfunction']
    lines += ['endpackage', '']
    package = ROOT / 'rtl/core/lpu_native_config_pkg.sv'
    package.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    identity = dict(schema_version=1, cmodel_base=index['cmodel_base'],
                    working_reference='local c7 + synchronous-read R1 + G/T decoupling',
                    index_sha256=sha(index_path), package_sha256=sha(package), profiles=rows,
                    cmodel_source_sha256={p: sha(cm/p) for p in [
                        'include/ftlpu/core/hardware_params.hpp', 'include/ftlpu/mem/mem_array.hpp',
                        'cmake/FTLPUHardwareConfig.cmake', 'cmake/hardware_config.hpp.in']})
    (ROOT/'config/native_profiles.manifest.json').write_text(
        json.dumps(identity, indent=2)+'\n', encoding='utf-8')
    return identity


if __name__ == '__main__':
    argparse.ArgumentParser(description=__doc__).parse_args()
    print(json.dumps(generate(), indent=2))
