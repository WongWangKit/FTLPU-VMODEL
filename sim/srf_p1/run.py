def with_srf_checkers(sources):
    """Mirror current simulation filelists without rebinding frozen old snapshots.

    Pre-native snapshots have no lane module to bind. Their saved filelists
    predate this checker; never map its new path into those old snapshots.
    """
    sources = [Path(p) for p in sources]
    current = [rel for rel in SRF if any(p.resolve() == ROOT / rel for p in sources)]
    sources = [p for p in sources if not any(p.as_posix().endswith('/' + rel)
                                           for rel in SRF_CHECKER_FILES)]
    if current:
        sources.append(ROOT / SRF_CHECKER)
        sources.extend(ROOT / SRF_BINDINGS[rel] for rel in current)
    return sources

def sha(p): return hashlib.sha256(Path(p).read_bytes()).hexdigest()
