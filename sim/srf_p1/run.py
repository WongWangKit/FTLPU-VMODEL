def git(root,*args):
    return subprocess.check_output(['git','-c','safe.directory='+root.as_posix(),'-C',str(root),*args],text=True).strip()
def execute(args,cwd,log,timeout=180):
    args=[str(a) for a in args]
    actual=args
    if args[0].lower().endswith(('.bat','.cmd')):
        # Batch argument scanning otherwise splits unquoted NAME=value plusargs.
        # All arguments here are paths/flags generated by this runner, not shell code.
        actual=os.environ.get('COMSPEC','cmd.exe')+' /d /s /c "'+' '.join('"'+a+'"' for a in args)+'"'
    with Path(log).open('w',encoding='utf-8') as f:
        f.write('COMMAND '+subprocess.list2cmdline(args)+'\n'); f.flush()
        p=subprocess.Popen(actual,cwd=cwd,stdout=f,stderr=subprocess.STDOUT)
        try: code=p.wait(timeout=timeout)
        except subprocess.TimeoutExpired:
            subprocess.run(['taskkill','/PID',str(p.pid),'/T','/F'],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
            p.wait(); code=-999
    return dict(command=args,exit=code,log=str(log),timeout=(code==-999))
def required(args,cwd,log):
    r=execute(args,cwd,log)
    if r['exit']!=0: raise RuntimeError(f"command failed: {log}")
    return r
