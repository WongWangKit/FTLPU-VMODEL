`timescale 1ns/1ps
// Complete shared SXM + zero-payload native WriteTap shell.
// Batch/MEM entry is MATRIX only; ROW/P/RUN and raw/API retain original ports.
// Existing MEM/SRF provide observed valid/busy/fault, without payload copies.
module sxm_triangle_writetap_core #(
  parameter integer T=4, TIMER_BITS=16, PORT_STREAMS=32, DEPTH=4096,
  localparam integer RAW_BITS=((240+8*T*(T<4?5:$clog2(8*T))+8+(T<4?3:$clog2(T)+1)+31)/32)*32
) (
  input wire clk_i, rst_ni,
  // op 1: context, 2: private tile config, 3: reserve input stripe.
  // op3 data[7:0] is a source-slot mask (0 means all T for C814).
  // Explicit partial reservation lets a single vector finish independently.
  input wire ctrl_valid_i,
  input wire [1:0] ctrl_op_i,
  input wire ctrl_ctx_i,
  input wire [2:0] ctrl_index_i,
  input wire [127:0] ctrl_data_i,
  input wire cap_valid_i, cap_ctx_i,
  input wire [2:0] cap_tile_i, cap_group_i,
  input wire [3:0] cap_row_i, // 0..7 row, 8 = complete block
  input wire p_valid_i, p_ctx_i,
  input wire [2:0] p_dest_i, p_source_i,
  input wire [3:0] p_row_i, // 8 = block; 9..15 = consume row 0..6
  input wire p_paired_i, p_branch_i,
  input wire [5:0] p_sequence_i,
  // Finite per-tile output program. First send = launch + delay + 1.
  input wire [T-1:0] run_valid_i,
  input wire run_ctx_i,
  input wire [TIMER_BITS-1:0] run_delay_i, run_interval_i,
  input wire [5:0] run_count_i, run_sequence_i,
  output wire [T*PORT_STREAMS*6-1:0] sr_read_req_o,
  input wire [T*PORT_STREAMS-1:0] sr_read_valid_i,
  input wire [T*PORT_STREAMS*64-1:0] sr_read_data_i,
  output wire [T*PORT_STREAMS-1:0] sr_consume_o,
  output wire [T*PORT_STREAMS-1:0] sr_write_valid_o,
  output wire [T*PORT_STREAMS*6-1:0] sr_write_sel_o,
  output wire [T*PORT_STREAMS*64-1:0] sr_write_data_o,
  output wire [3:0] fault_o, // ctrl, capture, P, output program
  output wire busy_o,
  input wire compat_t_valid_i, compat_p_valid_i,
  input wire [1:0] compat_t_family_i, compat_p_family_i,
  input wire [RAW_BITS-1:0] compat_t_raw_i, compat_p_raw_i,
  output wire [3:0] compat_fault_o,
  input wire batch_job_i,
  input wire [1:0] batch_mode_i,batch_dtype_i,
  input wire [15:0] batch_count_i,
  input wire [T*24-1:0] batch_lane_map_i,
  input wire [T*$clog2(T)-1:0] batch_tile_map_i,
  output wire batch_ready_o,batch_fault_o,
  input wire [T-1:0] batch_cap_valid_i,
  input wire [T*8-1:0] batch_lane_valid_i,
  input wire [T*2048-1:0] batch_cap_data_i,
  output wire [T-1:0] batch_cap_accept_o,
  output wire [T-1:0] batch_block_valid_o,batch_block_fp32_o,batch_block_vector_o,
  output wire [T*2048-1:0] batch_block_data_o,
  output wire [T*16-1:0] batch_block_matrix_o,
  output wire [T*$clog2(T)-1:0] batch_block_column_o,
  input wire resources_ready_i,input wire [14:0] base_i,
  input wire [3:0] mem_busy_i,mem_fault_i,input wire transport_fault_i,
  input wire [31:0] read_issue_valid_i,input wire [32*T-1:0] tap_data_valid_i,
  output wire [T*32-1:0] stream_valid_o,output wire [T*2048-1:0] stream_data_o,
  output wire [31:0] mem_issue_valid_o,output wire [1023:0] mem_issue_o,
  output wire [4*T-1:0] target_tap_o,output wire [4*T*15-1:0] target_address_o,
  output wire [32*T-1:0] tap_sample_o,
  output wire [31:0] committed_segments_o,output wire done_o,completion_fault_o,
  output wire pending_o,writer_busy_o,writer_fault_o,bad_o,monitor_bad_o
);
 wire start,core_ready,core_busy,writer_ready,writer_busy,writer_fault,pending,bad,monitor_bad;
 wire [T-1:0] block_ready;
 assign pending_o=pending;assign writer_busy_o=writer_busy;assign writer_fault_o=writer_fault;assign bad_o=bad;assign monitor_bad_o=monitor_bad;
 sxm_triangle_full_core #(.T(T),.TIMER_BITS(TIMER_BITS),.PORT_STREAMS(PORT_STREAMS)) u_full(
  .rst_ni,
  .clk_i(clk_i),
  .ctrl_valid_i(ctrl_valid_i),
  .ctrl_op_i(ctrl_op_i),
  .ctrl_ctx_i(ctrl_ctx_i),
  .ctrl_index_i(ctrl_index_i),
  .ctrl_data_i(ctrl_data_i),
  .cap_valid_i(cap_valid_i),
  .cap_ctx_i(cap_ctx_i),
  .cap_tile_i(cap_tile_i),
  .cap_group_i(cap_group_i),
  .cap_row_i(cap_row_i),
  .p_valid_i(p_valid_i),
  .p_ctx_i(p_ctx_i),
  .p_dest_i(p_dest_i),
  .p_source_i(p_source_i),
  .p_row_i(p_row_i),
  .p_paired_i(p_paired_i),
  .p_branch_i(p_branch_i),
  .p_sequence_i(p_sequence_i),
  .run_valid_i(run_valid_i),
  .run_ctx_i(run_ctx_i),
  .run_delay_i(run_delay_i),
  .run_interval_i(run_interval_i),
  .run_count_i(run_count_i),
  .run_sequence_i(run_sequence_i),
  .sr_read_req_o(sr_read_req_o),
  .sr_read_valid_i(sr_read_valid_i),
  .sr_read_data_i(sr_read_data_i),
  .sr_consume_o(sr_consume_o),
  .sr_write_valid_o(sr_write_valid_o),
  .sr_write_sel_o(sr_write_sel_o),
  .sr_write_data_o(sr_write_data_o),
  .fault_o(fault_o),
  .busy_o(core_busy),
  .compat_t_valid_i(compat_t_valid_i),
  .compat_p_valid_i(compat_p_valid_i),
  .compat_t_family_i(compat_t_family_i),
  .compat_p_family_i(compat_p_family_i),
  .compat_t_raw_i(compat_t_raw_i),
  .compat_p_raw_i(compat_p_raw_i),
  .compat_fault_o(compat_fault_o),
  .batch_job_i(start),
  .batch_mode_i(batch_mode_i),
  .batch_dtype_i(batch_dtype_i),
  .batch_count_i(batch_count_i),
  .batch_lane_map_i(batch_lane_map_i),
  .batch_tile_map_i(batch_tile_map_i),
  .batch_ready_o(core_ready),
  .batch_fault_o(batch_fault_o),
  .batch_cap_valid_i(batch_cap_valid_i),
  .batch_lane_valid_i(batch_lane_valid_i),
  .batch_cap_data_i(batch_cap_data_i),
  .batch_cap_accept_o(batch_cap_accept_o),
  .batch_block_ready_i(block_ready),
  .batch_block_valid_o(batch_block_valid_o),
  .batch_block_fp32_o(batch_block_fp32_o),
  .batch_block_vector_o(batch_block_vector_o),
  .batch_block_data_o(batch_block_data_o),
  .batch_block_matrix_o(batch_block_matrix_o),
  .batch_block_column_o(batch_block_column_o));
 lpu_sxm_triangle_mem_adapter #(.T(T),.DEPTH(DEPTH)) u_writer(
 .clk_i,.rst_ni,.job_valid_i(start),.fp32_i(batch_dtype_i[0]),.resources_ready_i(resources_ready_i && batch_mode_i==0 && batch_dtype_i<=1),
 .matrices_i(batch_count_i),.base_i,.tile_map_i(batch_tile_map_i),.job_ready_o(writer_ready),
 .block_valid_i(batch_block_valid_o),.block_fp32_i(batch_block_fp32_o),.block_data_i(batch_block_data_o),
 .block_matrix_i(batch_block_matrix_o),.block_column_i(batch_block_column_o),.block_ready_o(block_ready),
 .stream_valid_o,.stream_data_o,.mem_issue_valid_o,.mem_issue_o,.target_tap_o,.target_address_o,.busy_o(writer_busy),.fault_o(writer_fault));
 lpu_sxm_writetap_completion #(.T(T),.DEPTH(DEPTH)) u_completion(
 .clk_i,.rst_ni,.job_valid_i(batch_job_i),.fp32_i(batch_dtype_i[0]),.matrices_i(batch_count_i),
 .core_ready,.writer_ready,.core_busy,.writer_busy,.core_fault(batch_fault_o),.writer_fault,
 .mem_busy(mem_busy_i),.mem_fault(mem_fault_i),.transport_fault(transport_fault_i),.read_issue_valid_i,
 .wi(mem_issue_valid_o),.wc(mem_issue_o),.target(target_tap_o),.target_addr(target_address_o),.tap_data_valid_i,
 .job_ready_o(batch_ready_o),.start,.busy_o,.fault_o(completion_fault_o),.pending_q(pending),.bad_q(bad),.monitor_bad,
 .tap_sample_o,.committed_segments_o,.done_o);
endmodule
