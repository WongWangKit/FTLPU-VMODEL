"""Generate the storage-less v1 ROW controller from the reviewed legacy source.
Only storage ownership/mapping changes; P/pair/RUN control is reused verbatim.
Generator assertions make upstream changes explicit rather than silently drift.
"""
from pathlib import Path
import re,hashlib
R=Path(__file__).resolve().parents[3]/'lpu_src/FTLPU-VMODEL'
p=R/'rtl/sxm_native/sxm_row_core.sv';s=p.read_text(encoding='utf-8-sig')
s=s.replace('module sxm_row_core #(', 'module sxm_triangle_row_frontend #(')
s=s.replace('localparam integer SLOTS = T*T','localparam integer SLOTS = T*(T+1)/2')
s=s.replace('output wire [T*1024-1:0] compat_read_data_o','output wire [T*1024-1:0] compat_read_data_o,\n  input wire [SLOTS*2048-1:0] pool_read_i,\n  output reg [SLOTS*8-1:0] pool_write_rows_o,\n  output reg [SLOTS*2048-1:0] pool_write_data_o')
s=s.replace('reg [31:0] data_q [0:7][0:SLOTS-1][0:7];','wire [31:0] data_q [0:7][0:SLOTS-1][0:7];\n  for(genvar slot_view=0;slot_view<SLOTS;slot_view++)for(genvar q_view=0;q_view<8;q_view++)for(genvar r_view=0;r_view<8;r_view++)\n    assign data_q[q_view][slot_view][r_view]=pool_read_i[slot_view*2048+(r_view*8+q_view)*32+:32];')
s=s.replace('sid = context_q[cx][115] ? s*T+a : a*T+s;', 'sid = s*(s+1)/2 + a%(s+1); // Logical layout is independent of physical source ring.')
s=s.replace('sid = s*(s+1)/2 + a%(s+1); // Logical layout is independent of physical source ring.', '''integer ss,aa;
    begin
      // Both operands are bounded Tile IDs. Elaborate a constant truth table,
      // not a general 32-bit variable divider/modulo datapath.
      sid=0;
      for(ss=0;ss<T;ss=ss+1)for(aa=0;aa<T;aa=aa+1)
        if(s==ss && a==aa)sid=ss*(ss+1)/2+aa%(ss+1);
    end''')
start=s.index('      if(COMPAT_STORAGE!=0) begin',s.index('always @(posedge'))
end=s.index('      pipe_valid_q<=0;',start)
s=s[:start]+s[end:]
start=s.index('          for(z=0;z<8;z=z+1) begin',s.index('if(cap_valid_i && cap_ok) begin',s.index('always @(posedge')))
end=s.index('          written_q[cs][rr]<=1;',start)
s=s[:start]+s[end:]
assert '<=incoming' not in s and 'data_q[cq][ct][cr] <=' not in s
# Keep one shared value_at read, then decode the destination with fixed slices.
# Dynamic packed insertion p_dest*PORT_STREAMS+r*planes+q creates a very large
# intermediate mux network, even though the legal destination set is bounded.
start=s.index('    if(p_valid_i && p_ok && p_block) begin')
end=s.index('  assign busy_o=',start)
assert s[start:end].endswith('  end\n')
s=s[:start]+'''    if(p_valid_i && p_ok && p_block) begin
      for(d=0;d<T;d=d+1)if(int'(p_dest_i)==d)begin
        for(i=0;i<PORT_STREAMS;i=i+1)begin
          sr_write_sel_o[(d*PORT_STREAMS+i)*6+:6]=selector_at(tile_q[p_ctx_i][p_dest_i[TW-1:0]],i);
          if(i<(context_q[p_ctx_i][114]?32:16))sr_write_valid_o[d*PORT_STREAMS+i]=1;
        end
      end
      for(r=0;r<8;r=r+1)for(l=0;l<8;l=l+1)begin
        word_value=value_at(ps,int'(p_ctx_i),int'(p_dest_i),r,l);
        for(d=0;d<T;d=d+1)if(int'(p_dest_i)==d)for(q=0;q<4;q=q+1)begin
          if(context_q[p_ctx_i][114])begin
            if(r*4+q<PORT_STREAMS)sr_write_data_o[(d*PORT_STREAMS+r*4+q)*64+l*8+:8]=word_value[q*8+:8];
          end else if(q<2)sr_write_data_o[(d*PORT_STREAMS+r*2+q)*64+l*8+:8]=word_value[q*8+:8];
        end
      end
    end
  end
'''+s[end:]
write='''
  integer wr_slot,wr_row,wr_lane,wr_plane;
  reg [31:0] wr_word;
  always @* begin
    pool_write_rows_o=0;pool_write_data_o=0;wr_word=0;
    for(wr_slot=0;wr_slot<SLOTS;wr_slot=wr_slot+1)
    if(cap_valid_i && cap_ok && cs==wr_slot)for(wr_row=0;wr_row<8;wr_row=wr_row+1)if(cap_block || wr_row==int'(cap_row_i))begin
      pool_write_rows_o[wr_slot*8+wr_row]=1;
      for(wr_lane=0;wr_lane<8;wr_lane=wr_lane+1)begin
        wr_word=0;
        for(wr_plane=0;wr_plane<4;wr_plane=wr_plane+1)if(wr_plane<planes)
          wr_word[wr_plane*8+:8]=sr_read_data_i[(cap_tile_i*PORT_STREAMS+(cap_block?wr_row*planes:0)+wr_plane)*64+wr_lane*8+:8];
        pool_write_data_o[wr_slot*2048+(wr_row*8+wr_lane)*32+:32]=wr_word;
      end
    end
  end
'''
s=s.replace('  integer x,y,z,branch,pl,rr,slot;',write+'\n  integer x,y,z,branch,pl,rr,slot;')
s='// Generated by build_shared_frontend.py; source SHA256 '+hashlib.sha256(p.read_bytes()).hexdigest()+'\n'+s
(R/'rtl/sxm_native/sxm_triangle_row_frontend.sv').write_text(s,encoding='utf-8')
print('generated storage-less ROW frontend; source slots = T*(T+1)/2')

# Reuse the legacy SR mux/arbitration wiring, adding the third exclusive owner.
s=(R/'rtl/sxm_native/sxm_compatible_core.sv').read_text(encoding='utf-8-sig')
s=s.replace('module sxm_compatible_core #(', 'module sxm_triangle_full_core #(')
s=s.replace('output wire [3:0] compat_fault_o\n', '''output wire [3:0] compat_fault_o,
  input wire batch_job_i,
  input wire [1:0] batch_mode_i,batch_dtype_i,
  input wire [15:0] batch_count_i,
  input wire [T*24-1:0] batch_lane_map_i,
  input wire [T*$clog2(T)-1:0] batch_tile_map_i,
  output wire batch_ready_o,batch_fault_o,
  input wire [T-1:0] batch_cap_valid_i,
  input wire [T*8-1:0] batch_lane_valid_i,
  input wire [T*2048-1:0] batch_cap_data_i,
  output wire [T-1:0] batch_cap_accept_o,
  input wire [T-1:0] batch_block_ready_i,
  output wire [T-1:0] batch_block_valid_o,batch_block_fp32_o,batch_block_vector_o,
  output wire [T*2048-1:0] batch_block_data_o,
  output wire [T*16-1:0] batch_block_matrix_o,
  output wire [T*$clog2(T)-1:0] batch_block_column_o
''')
s=s.replace('wire row_busy,legacy_busy;', '''wire row_busy,legacy_busy,typed_busy,typed_ready;
  localparam integer SLOTS=T*(T+1)/2;
  wire [SLOTS*8-1:0] pool_wr;
  wire [SLOTS*2048-1:0] pool_rd,pool_wd;
  wire batch_any=batch_job_i || (|batch_cap_valid_i);
  wire typed_accept=!row_busy && !legacy_busy && !row_any && !legacy_any;
  assign batch_ready_o=typed_ready && typed_accept;
''')
s=s.replace('wire row_accept=!legacy_busy && (!legacy_any || row_busy);','wire row_accept=!typed_busy && !batch_job_i && !legacy_busy && (!legacy_any || row_busy);')
s=s.replace('wire legacy_accept=!row_busy && !(row_any && !legacy_busy);','wire legacy_accept=!typed_busy && !batch_job_i && !row_busy && !(row_any && !legacy_busy);')
s=s.replace('wire use_legacy=legacy_busy || (legacy_any && !row_busy && !row_any);','wire use_legacy=legacy_busy || (legacy_any && !row_busy && !row_any && !typed_busy && !batch_job_i);')
s=s.replace('(legacy_any && !legacy_accept);','(legacy_any && !legacy_accept) || (batch_any && !typed_accept);')
s=s.replace('assign busy_o=row_busy || legacy_busy;', 'assign busy_o=row_busy || legacy_busy || typed_busy;')
s=s.replace('sxm_row_core #(.T(T),.TIMER_BITS(TIMER_BITS),.COMPAT_STORAGE(1),', 'sxm_triangle_row_frontend #(.T(T),.TIMER_BITS(TIMER_BITS),.COMPAT_STORAGE(0),')
s=s.replace('.compat_write_rows_i(bank_wr),\n    .compat_write_data_i(bank_wdata),\n    .compat_read_data_o(bank_rdata));', ".compat_write_rows_i('0),\n    .compat_write_data_i('0),\n    .compat_read_data_o(),.pool_read_i(pool_rd),.pool_write_rows_o(pool_wr),.pool_write_data_o(pool_wd));")
typed='''
  sxm_triangle_core #(.T(T),.TIMER_BITS(TIMER_BITS),.COMPAT_STORAGE(1),.SHARED_ROW(1)) u_storage(
    .clk_i,.rst_ni,.job_valid_i(batch_job_i && typed_accept),.mode_i(batch_mode_i),.dtype_i(batch_dtype_i),.count_i(batch_count_i),
    .lane_map_i(batch_lane_map_i),.tile_map_i(batch_tile_map_i),.job_ready_o(typed_ready),
    .cap_valid_i(batch_cap_valid_i & {T{typed_accept}}),.cap_lane_valid_i(batch_lane_valid_i),.cap_data_i(batch_cap_data_i),.cap_accept_o(batch_cap_accept_o),
    .block_ready_i(batch_block_ready_i),.block_valid_o(batch_block_valid_o),.block_fp32_o(batch_block_fp32_o),.block_vector_o(batch_block_vector_o),
    .block_data_o(batch_block_data_o),.block_matrix_o(batch_block_matrix_o),.block_column_o(batch_block_column_o),.busy_o(typed_busy),.fault_o(batch_fault_o),
    .compat_write_rows_i(bank_wr),.compat_write_data_i(bank_wdata),.compat_read_data_o(bank_rdata),
    .pool_write_rows_i(pool_wr),.pool_write_data_i(pool_wd),.pool_read_o(pool_rd));
'''
s=s.replace('`ifndef SYNTHESIS',typed+'\n`ifndef SYNTHESIS')
s=s.replace('if(row_busy && legacy_busy)', 'if((row_busy && legacy_busy) || (typed_busy && (row_busy || legacy_busy)))')
s='// Generated by build_shared_frontend.py; one physical triangle pool.\n'+s
(R/'rtl/sxm_native/sxm_triangle_full_core.sv').write_text(s,encoding='utf-8')
print('generated full shared triangle/ROW/raw wrapper')
