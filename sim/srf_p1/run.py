    rows=make_vectors(out)
    required([out/'reference.exe',out/'vectors.txt',out/'expected.txt'],out,out/'reference_run.txt')
    for p in ['config/ftlpu-lpu32.json','cmake/FTLPUHardwareConfig.cmake','cmake/hardware_config.hpp.in',
              'include/ftlpu/core/stream_fabric.hpp','include/ftlpu/core/stream_port.hpp','include/ftlpu/core/stream.hpp','include/ftlpu/core/hardware_params.hpp','include/ftlpu/core/stream_topology_descriptor.hpp']:
        if (CM/p).exists():
            target=out/'reference_source'/p; target.parent.mkdir(parents=True,exist_ok=True); shutil.copy2(CM/p,target)
    files={p.relative_to(out).as_posix():sha(p) for d in [snapshot,out/'generated',out/'reference_source'] for p in d.rglob('*') if p.is_file()}
    files.update({p:sha(out/p) for p in ['reference.exe','vectors.txt','expected.txt','cases.json','inventory.json','original_hashes.json']})
    verification={p.relative_to(ROOT).as_posix():sha(p) for p in HERE.iterdir() if p.is_file()}
