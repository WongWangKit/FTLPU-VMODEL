def inventory():
    entries=[]
    for fl in sorted((ROOT/'sim').glob('*.f')):
        text=fl.read_text(encoding='utf-8-sig')
        if 'rtl/srf/' not in text: continue
        files=[s.strip() for s in text.splitlines() if s.strip() and not s.strip().startswith('#')]
        tbs=[p for p in files if p.startswith('sim/tb/')]
        modules=re.findall(r'\bmodule\s+(\w+)',(ROOT/tbs[-1]).read_text())
        top=Path(tbs[-1]).stem
        if top not in modules: raise RuntimeError('explicit top required for '+tbs[-1])
        entries.append(dict(filelist=fl.relative_to(ROOT).as_posix(),files=files,top=top))
    refs=[]; instances=[]
    for directory in ['rtl','sim','scripts']:
        for p in (ROOT/directory).rglob('*'):
            if not p.is_file() or p.suffix not in ('.sv','.v','.ps1','.tcl','.xdc','.f'): continue
            if 'srf_p1' in p.parts: continue
            for n,line in enumerate(p.read_text(encoding='utf-8-sig',errors='replace').splitlines(),1):
                if 'ftlpu_sr_' in line and p.parent.name!='srf':
                    instances.append(dict(path=p.relative_to(ROOT).as_posix(),line=n,text=line.strip()))
                if re.search(r'\b(?:u_leaf|u_column|u_srf|u_hemisphere|u_direction)\.|\b(?:valid_state_q|data_state_q)\b',line) and p.parent.name!='srf':
                    refs.append(dict(path=p.relative_to(ROOT).as_posix(),line=n,text=line.strip()))
    return dict(modify=SRF,callers=entries,external_hierarchy_candidates=refs,instance_references=instances)

def make_vectors(out):
    rows=[]
    def add(name,reset=0,b=(),i=(),c=(),negative=False):
        rows.append(dict(seq=len(rows),name=name,reset=reset,b=list(b),i=list(i),c=list(c),negative=negative))
    def data(h,d,c,t,s,k):
        return sum(((h*101+d*53+c*17+t*31+s*7+k*19+l*23)&255)<<(8*l) for l in range(8))
    add('reset_empty',1)
    # All coordinates and both slots see full-segment traffic; consume suppresses
    # old passive traffic, permitting new same-column injection each cycle.
    prior=[]
    for slot in range(2):
        inj=[(h,d,c,t,slot,s,data(h,d,c,t,s,slot)) for h in range(2) for d in range(2)
             for c in range(16) for t in range(4) for s in range(32)]
        con=[(*q[:4],k,q[5]) for q in prior for k in range(2)]
        add('all_coordinates_slot_'+str(slot),i=inj,c=con); prior=inj
    add('all_coordinates_dual_consume',c=[(*q[:4],k,q[5]) for q in prior for k in range(2)])
    add('empty_after_consumption')
    # Dense simultaneous east/west boundary streams, then drain all sixteen hops.
    for tick in range(20):
        b=[(h,d,t,s,data(h,d,tick,t,s,tick)) for h in range(2) for d in range(2) for t in range(4) for s in range(32)]
        # Last-column consumption tests exit suppression without affecting entry.
        c=[] if tick<16 or tick%2==0 else [(h,d,15 if d==0 else 0,t,0,s) for h in range(2) for d in range(2) for t in range(4) for s in range(32)]
        add('boundary_stream_'+str(tick),b=b,c=c)
    for tick in range(17): add('drain_'+str(tick))
    add('mid_reset_with_data',i=[(0,0,4,1,0,7,0x123456789ABCDEF0)])
    add('reset_drops_inflight',1)
    # Fixed-seed legacy random compatibility smoke, NOT D04 acceptance random.
    rng=random.Random(0x535246); state={}
    for tick in range(96):
        consumed={key for key in state if rng.randrange(3)==0}
        c=[(h,d,col,t,k,s) for h,d,col,t,s in sorted(consumed) for k in range(1+rng.randrange(2))]
        reserved={(h,d,col+(1 if d==0 else -1),t,s) for h,d,col,t,s in state if (h,d,col,t,s) not in consumed and 0<=col+(1 if d==0 else -1)<16}
        i=[]; b=[]
        for j in range(48):
            h,d,col,t,s=rng.randrange(2),rng.randrange(2),rng.randrange(16),rng.randrange(4),rng.randrange(32)
            key=(h,d,col,t,s)
            if key in reserved: continue
            reserved.add(key); i.append((h,d,col,t,rng.randrange(2),s,rng.getrandbits(64)))
        add('legacy_random_'+str(tick),i=i,c=c)
        state=oracle(state,rows[-1])[0]
    add('reset_before_negatives',1)
    # Each illegal cycle is isolated, and other coordinates continue correctly.
    for h,d in [(0,0),(0,1),(1,0),(1,1)]:
        col=0 if d==0 else 15; nxt=col+(1 if d==0 else -1)
        a=(h,d,col,0,0,0,0x0807060504030201)
        other=(1-h,1-d,7,3,1,31,0xE7D6C5B4A3928170)
        for same in [False,True]:
            add(f'double_producer_h{h}d{d}_same{same}',1,i=[a,(*a[:4],1,0,a[-1] if same else ~a[-1]&((1<<64)-1)),other],negative=True)
        add(f'boundary_collision_h{h}d{d}',1,b=[(h,d,0,0,7)],i=[a,other],negative=True)
        for three in [False,True]:
            add('warm_link',1,i=[a])
            ii=[(h,d,nxt,0,0,0,9),other]
            if three: ii.append((h,d,nxt,0,1,0,10))
            add(f'link_collision_h{h}d{d}_three{three}',i=ii,negative=True)
        for consumers in [1,2]:
            add(f'invalid_consume_h{h}d{d}_k{consumers}',1,i=[other],c=[(h,d,col,0,k,0) for k in range(consumers)],negative=True)
        add(f'both_faults_h{h}d{d}',1,i=[a,(*a[:4],1,0,a[-1]),other],c=[(h,d,col,0,0,0)],negative=True)
    add('reset_after_negatives',1)
    save(out/'cases.json',rows)
    with (out/'vectors.txt').open('w',encoding='ascii') as f:
        for r in rows:
            f.write(f"{r['seq']} {r['reset']} {len(r['b'])} {len(r['i'])} {len(r['c'])}\n")
            for e in r['b']+r['i']: f.write(' '.join(map(str,e[:-1]))+f' {e[-1]:016x}\n')
            for e in r['c']: f.write(' '.join(map(str,e))+'\n')
    return rows

def si(q):
    h,d,c,t,s=q; return ((((h*2+d)*16+c)*4+t)*32+s)
def bi(q):
    h,d,t,s=q; return ((h*2+d)*4+t)*32+s
def fi(q):
    h,d,c,t,s=q; return ((h*2+d)*16+c)*4+t
def oracle(state,row):
    if row['reset']: state={}
    consumed={(h,d,c,t,s) for h,d,c,t,k,s in row['c']}
    candidates={}; boundary={}; invalid=0
    def put(key,val): candidates.setdefault(key,[]).append(val)
    for q in consumed:
        if q not in state: invalid|=1<<fi(q)
    for (h,d,c,t,s),value in state.items():
        if (h,d,c,t,s) in consumed: continue
        dst=c+(1 if d==0 else -1)
        if 0<=dst<16: put((h,d,dst,t,s),value)
        else: boundary[(h,d,t,s)]=value
    for h,d,t,s,v in row['b']: put((h,d,0 if d==0 else 15,t,s),v)
    for h,d,c,t,p,s,v in row['i']: put((h,d,c,t,s),v)
    nxt={}; collision=0
    for key,values in candidates.items():
        if len(values)>1: collision|=1<<fi(key)
        else: nxt[key]=values[0]
    return nxt,boundary,collision,invalid

def sim(tools,engine,sources,top,work,plus=(),vectors_root=None):
    sources=with_srf_checkers(sources)
    work.mkdir(parents=True,exist_ok=False)
    if vectors_root and (vectors_root/'sim/vectors').is_dir():
        shutil.copytree(vectors_root/'sim/vectors',work/'sim/vectors')
    result={'engine':engine,'top':top,'steps':[],'pass':False}
    if engine=='xsim':
        commands=[('compile',[tools['xvlog.bat'],'--sv',*sources]),
                  ('elaborate',[tools['xelab.bat'],top,'-s','p1_sim','--debug','typical','--O0']),
                  ('simulate',[tools['xsim.bat'],'p1_sim','-runall',*[v for p in plus for v in ('-testplusarg',p)]])]
    else:
        commands=[('compile',[tools['iverilog'],'-g2012','-s',top,'-o',str(work/'sim.vvp'),*sources]),
                  ('simulate',[tools['vvp'],str(work/'sim.vvp'),*['+'+p for p in plus]])]
    for stage,cmd in commands:
        r=execute(cmd,work,work/(stage+'.txt'),180); r['stage']=stage; result['steps'].append(r)
        if r['exit']!=0:
            result['failure']=stage; break
    else:
        log=(work/'simulate.txt').read_text(encoding='utf-8',errors='replace')
        result['pass']=bool(re.search(r'(?:TEST_PASS|SRF_P1_LEGACY_TRACE PASS)',log)) and not re.search(r'(?:TEST_FAIL|Fatal:|FATAL:|ERROR:)',log)
        if not result['pass']: result['failure']='missing_pass_or_simulation_error'
    save(work/'result.json',result)
    print(engine,top,'PASS' if result['pass'] else result.get('failure'),flush=True)
    return result

def parse_bus(v,d):
    valid=int(v,16); result={}
    while valid:
        low=valid&-valid; bit=low.bit_length()-1
        # Do not parse invalid payload: X/Z there is explicitly nonarchitectural.
        # Unknown valid or unknown effective payload still fails conversion.
        word=int(d[len(d)-(bit+1)*16:len(d)-bit*16],16)
        result[bit]=word; valid-=low
    return result
def compare(out,trace):
    cases=read(out/'cases.json'); state={}; failures=[]; n=0; negative=0
    with (out/'expected.txt').open() as ef, Path(trace).open() as tf:
        for row in cases:
            e=ef.readline().split(); a=tf.readline().split()
            if len(e)!=6 or len(a)!=7: raise RuntimeError('truncated or malformed trace')
            if int(e[0])!=row['seq'] or int(a[0])!=row['seq']: raise RuntimeError('cycle identity mismatch')
            nxt,bo,col,inv=oracle(state,row)
            is_bad=bool(col or inv)
            if is_bad!=row['negative']: raise RuntimeError('vector legality checker failed '+row['name'])
            if (e[1]!='none')!=is_bad: raise RuntimeError('CModel exception disagreement '+row['name'])
            if e[1]!='none' and e[1]!=('invalid' if inv else 'collision'): raise RuntimeError('wrong first exception')
            expected_state={si(q):v for q,v in nxt.items()}
            if not is_bad:
                cmstate=parse_bus(e[4],e[5])
                if cmstate!=expected_state: raise RuntimeError('independent oracle vs CModel disagreement '+row['name'])
                expected_state=cmstate
            expected_boundary=parse_bus(e[2],e[3])
            if expected_boundary!={bi(q):v for q,v in bo.items()}: raise RuntimeError('boundary oracle disagreement')
            actual_state=parse_bus(a[5],a[6]); actual_boundary=parse_bus(a[1],a[2])
            for kind,expected,actual in [('state',expected_state,actual_state),('boundary',expected_boundary,actual_boundary),('collision',col,int(a[3],16)),('invalid',inv,int(a[4],16))]:
                if expected!=actual:
                    detail={'seq':row['seq'],'case':row['name'],'kind':kind,'input':row,'prestate':{str(q):v for q,v in state.items()}}
                    if isinstance(expected,dict):
                        key=next(k for k in sorted(set(expected)|set(actual)) if expected.get(k)!=actual.get(k))
                        detail.update(index=key,expected=expected.get(key),actual=actual.get(key))
                    else: detail.update(expected=hex(expected),actual=hex(actual))
                    failures.append(detail); break
            if failures: break
            state=nxt; n+=1; negative+=is_bad
        if not failures and (tf.readline().strip() or ef.readline().strip()): raise RuntimeError('extra trace cycles')
    report=dict(pass_=not failures,cycles=n,negative_cycles=negative,failures=failures,
                scope='step5 legacy compatibility; NOT step6 acceptance',trace_sha256=sha(trace))
    save(Path(trace).with_suffix('.comparison.json'),report)
    if failures: raise RuntimeError('first divergence '+json.dumps(failures[0],ensure_ascii=False)[:1200])
    return report

def validate_manifest(out):
    m=read(out/'manifest.json')
    if m['params']!=PARAMS or m['cmodel_sha']!=CM_SHA or m['format']!=1: raise RuntimeError('manifest identity mismatch')
    for rel,h in m['files'].items():
        if sha(out/rel)!=h: raise RuntimeError('manifest file changed '+rel)
    for rel,h in m['verification_files'].items():
        if sha(ROOT/rel)!=h: raise RuntimeError('verification changed; create a new reviewed baseline: '+rel)
    return m

def prepare(out):
    out.mkdir(parents=True,exist_ok=False)
    if git(CM,'rev-parse','HEAD')!=CM_SHA or git(CM,'status','--porcelain','--untracked-files=no'):
        raise RuntimeError('CModel must be clean at fixed SHA')
    if git(ROOT,'rev-parse','HEAD')!=VM_SHA: raise RuntimeError('unexpected RTL starting commit')
    inv=inventory(); save(out/'inventory.json',inv)
    for p in SRF:
        blob=subprocess.check_output(['git','-c','safe.directory='+ROOT.as_posix(),'-C',str(ROOT),'show',VM_SHA+':'+p])
        if (ROOT/p).read_bytes().replace(b'\r\n',b'\n')!=blob.replace(b'\r\n',b'\n'):
            raise RuntimeError('RTL baseline already modified '+p)
    snapshot=out/'baseline_source'
    shutil.copytree(ROOT/'rtl',snapshot/'rtl')
    shutil.copytree(ROOT/'sim',snapshot/'sim',ignore=shutil.ignore_patterns('srf_p1'))
